using System.IO.Compression;
using System.Text.Json;
using SI.Management.Web.Data;

namespace SI.Management.Web.Cmdb;

/// One column of a hand-off object: its SQL (or JSON) type, whether it is always filled, what it means and which
/// ServiceNow field it maps to, with an example value from the sample rows.
public sealed record SnowPackColumn(string Name, string Type, string Required, string Meaning, string ServiceNow, string Example);

/// One sample row: the case it shows and its values as the import delivers them (null = NULL).
public sealed record SnowPackRow(string Case, IReadOnlyDictionary<string, string?> Values);

/// One hand-off object (an import view of the SQL channel, or an Import Set body of the REST channel).
public sealed record SnowPackObject(string Id, string Title, string Channel, string Source, string StagingTable, string Target, string File, bool Coming,
    IReadOnlyList<SnowPackColumn> Columns, IReadOnlyList<SnowPackRow> Rows);

/// One test case: what SecurityInsight sends and what the ServiceNow team should see.
public sealed record SnowPackCase(string Id, string Title, string Object, string What, string Expect, bool Coming);

public sealed record SnowPack(string Title, string Note, IReadOnlyList<SnowPackCase> Cases, IReadOnlyList<string> Checklist, IReadOnlyList<SnowPackObject> Objects)
{
    public SnowPackCase? CaseOf(string id) => Cases.FirstOrDefault(c => c.Id == id);
}

/// <summary>
/// THE SERVICENOW TEST PACK (operator, 2026-10-06): fictional sample rows for every object SecurityInsight hands to
/// ServiceNow, so the customer's ServiceNow developers can build and approve the integration before SecurityInsight is
/// live. Generated by setup\New-SIServiceNowTestPack.ps1 from the shipped view definitions (a Pester test fails when they
/// drift) and EMBEDDED in this assembly: the connector page reads it from here and offers the files as a zip.
/// </summary>
public static class ServiceNowTestPack
{
    public const string Prefix = "ServiceNowTestPack/";
    public const string ZipName = "securityinsight-servicenow-test-pack.zip";

    private static readonly Lazy<SnowPack> _pack = new(Read);

    public static SnowPack Pack => _pack.Value;

    /// Every file of the pack: its path inside the pack ("sql/vImportCi.csv", ...) and the embedded resource name.
    public static IReadOnlyList<(string Path, string Resource)> Files()
    {
        var asm = typeof(ServiceNowTestPack).Assembly;
        return asm.GetManifestResourceNames()
            .Select(n => (Name: n, Norm: n.Replace('\\', '/')))
            .Where(x => x.Norm.StartsWith(Prefix, StringComparison.Ordinal))
            .Select(x => (x.Norm[Prefix.Length..], x.Name))
            .OrderBy(x => x.Item1, StringComparer.Ordinal)
            .ToList();
    }

    private static Stream Open(string resource) =>
        typeof(ServiceNowTestPack).Assembly.GetManifestResourceStream(resource) ?? throw new InvalidOperationException("the ServiceNow test pack is not embedded: " + resource);

    private static SnowPack Read()
    {
        var file = Files().FirstOrDefault(f => f.Path == "servicenow-test-pack.json");
        if (file.Resource is null) throw new InvalidOperationException("the ServiceNow test pack is not embedded (servicenow-test-pack.json)");
        using var s = Open(file.Resource);
        using var doc = JsonDocument.Parse(s);
        var root = doc.RootElement;
        static string Str(JsonElement e, string n) => e.TryGetProperty(n, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() ?? "" : "";
        static bool Bool(JsonElement e, string n) => e.TryGetProperty(n, out var v) && v.ValueKind == JsonValueKind.True;
        var cases = root.GetProperty("cases").EnumerateArray()
            .Select(c => new SnowPackCase(Str(c, "id"), Str(c, "title"), Str(c, "object"), Str(c, "what"), Str(c, "expect"), Bool(c, "coming"))).ToList();
        var checklist = root.GetProperty("checklist").EnumerateArray().Select(x => x.GetString() ?? "").ToList();
        var objects = new List<SnowPackObject>();
        foreach (var o in root.GetProperty("objects").EnumerateArray())
        {
            var cols = o.GetProperty("columns").EnumerateArray()
                .Select(c => new SnowPackColumn(Str(c, "name"), Str(c, "type"), Str(c, "required"), Str(c, "meaning"), Str(c, "servicenow"), Str(c, "example"))).ToList();
            var rows = new List<SnowPackRow>();
            foreach (var r in o.GetProperty("rows").EnumerateArray())
            {
                var values = new Dictionary<string, string?>(StringComparer.Ordinal);
                foreach (var p in r.GetProperty("values").EnumerateObject())
                    values[p.Name] = p.Value.ValueKind == JsonValueKind.Null ? null : p.Value.ToString();
                rows.Add(new SnowPackRow(Str(r, "case"), values));
            }
            objects.Add(new SnowPackObject(Str(o, "id"), Str(o, "title"), Str(o, "channel"), Str(o, "source"), Str(o, "stagingTable"), Str(o, "target"), Str(o, "file"),
                Bool(o, "coming"), cols, rows));
        }
        return new SnowPack(Str(root, "title"), Str(root, "note"), cases, checklist, objects);
    }

    /// The whole pack as one zip (folder servicenow-test-pack/): the CSV per object, the Import Set bodies, the column
    /// dictionary, the JSON and the how-to. Built from the embedded files, byte for byte.
    public static byte[] Zip()
    {
        using var ms = new MemoryStream();
        using (var zip = new ZipArchive(ms, ZipArchiveMode.Create, leaveOpen: true))
        {
            foreach (var (path, resource) in Files())
            {
                var entry = zip.CreateEntry("servicenow-test-pack/" + path, CompressionLevel.Optimal);
                entry.LastWriteTime = new DateTimeOffset(2026, 10, 6, 0, 0, 0, TimeSpan.Zero);
                using var to = entry.Open();
                using var from = Open(resource);
                from.CopyTo(to);
            }
        }
        return ms.ToArray();
    }
}

/// The first rows of this install's own hand-off views (the Pro database's snowstage views), read only.
public sealed record SnowPreviewView(string View, bool Exists, IReadOnlyList<string> Columns, IReadOnlyList<IReadOnlyDictionary<string, string?>> Rows);

/// <summary>
/// "Preview with your data": the first few rows of the Pro database's ServiceNow hand-off views (snowstage.vImport*),
/// READ ONLY, for an Admin who wants to compare the sample with the real thing. A view that does not exist yet is
/// reported as such; nothing is ever written.
/// </summary>
public interface IServiceNowPreview
{
    Task<IReadOnlyList<SnowPreviewView>> ReadAsync(int top, CancellationToken ct);
}

public sealed class SqlServiceNowPreview : IServiceNowPreview
{
    private readonly ISqlExecutor _sql;
    public SqlServiceNowPreview(ISqlExecutor sql) => _sql = sql;

    /// The views previewed, in the order the page shows them.
    public static readonly IReadOnlyList<string> Views =
        ["snowstage.vImportCi", "snowstage.vImportCiKeyValue", "snowstage.vImportCiRelation", "snowstage.vProposedCi", "snowstage.vImportVulnerableItem"];

    /// One view's first rows, newest change first; a missing view answers one row with __missing = 1. The view name is
    /// one of the constant list above, never user input.
    public static string Sql(string view) => $"""
IF OBJECT_ID(N'{view}') IS NULL
    SELECT 1 AS __missing;
ELSE
    EXEC sp_executesql N'SELECT TOP (@Top) * FROM {view} ORDER BY u_changed_at DESC', N'@Top int', @Top = @Top;
""";

    public async Task<IReadOnlyList<SnowPreviewView>> ReadAsync(int top, CancellationToken ct)
    {
        var n = Math.Clamp(top, 1, 20);
        var output = new List<SnowPreviewView>();
        foreach (var v in Views)
        {
            var rows = await _sql.QueryAsync(Sql(v), new Dictionary<string, object?> { ["Top"] = n }, ct);
            if (rows.Count > 0 && rows[0].ContainsKey("__missing")) { output.Add(new SnowPreviewView(v, false, Array.Empty<string>(), Array.Empty<IReadOnlyDictionary<string, string?>>())); continue; }
            var cols = rows.Count > 0 ? rows[0].Keys.ToList() : new List<string>();
            var list = rows.Select(r => (IReadOnlyDictionary<string, string?>)r.ToDictionary(k => k.Key, k => Cell(k.Value), StringComparer.OrdinalIgnoreCase)).ToList();
            output.Add(new SnowPreviewView(v, true, cols, list));
        }
        return output;
    }

    /// A value as the import delivers it: dates "yyyy-MM-dd HH:mm:ss.fff" (UTC, as stored), bit 1 / 0.
    public static string? Cell(object? v) => v switch
    {
        null or DBNull => null,
        DateTime d => d.ToString("yyyy-MM-dd HH:mm:ss.fff", System.Globalization.CultureInfo.InvariantCulture),
        bool b => b ? "1" : "0",
        IFormattable f => f.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
        _ => v.ToString(),
    };
}
