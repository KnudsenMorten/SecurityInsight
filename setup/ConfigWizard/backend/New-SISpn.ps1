# Compute an admin-consent URL the wizard UI can surface to the operator. A
# Global Admin (or anyone with Privileged Role Administrator on the app) clicks
# this URL once and consents to all the requested permissions in a single
# Entra portal flow -- works regardless of whether the wizard's operator had
# the rights to do it themselves.
$consentUrl = "https://login.microsoftonline.com/$TenantId/adminconsent?client_id=$($app.AppId)"
# Counted over EVERY permission -- Graph, MTP and MDE. The counts above were taken after the Graph loop
# only, so a pending Machine.Read.All / AdvancedHunting.Read.All still reported "granted" and nobody was
# sent to the consent URL. @() because a single matching hashtable's .Count is its KEY count on PS 5.1.
$grantedCount = @($permResults | Where-Object { $_.Status -in @('granted','already') }).Count
$pendingCount = @($permResults | Where-Object { $_.Status -in @('pending','skipped') }).Count
$consentStatus = if ($pendingCount -eq 0) { 'granted' }
                 elseif ($grantedCount -eq 0) { 'pending' }
                 else { 'partial' }
_Info "consent status: $consentStatus"
if ($consentStatus -ne 'granted') {
    _Info "admin consent URL (hand to a Global Admin, then re-run /api/apply):"
    _Info "  $consentUrl"
}

# ----- 6. Azure RBAC -----
# The setup sign-in MUST exist before this cmdlet runs (Start-SetupWizard signs in first). NEVER sign in here -- in
# the wizard's listener nobody watches for a browser prompt (root cause of the v2.2.105-v2.2.112 listener stall).
_Step "verify the Azure sign-in"
$azCtx = Get-SISetupAzureContext
if (-not $azCtx) {
    throw "Nobody is signed in to Azure in this PowerShell session. Start the wizard again -- it signs you in: .\Start-SetupWizard.ps1 -TenantId $TenantId"
}
if ($azCtx.Tenant.Id -ne $TenantId) {
    throw ("Azure sign-in tenant mismatch: signed in to {0}, wizard wants {1}. Start the wizard again and sign in to that tenant: .\Start-SetupWizard.ps1 -TenantId {1}" -f $azCtx.Tenant.Id, $TenantId)
}
if (-not $azCtx.Subscription -or $azCtx.Subscription.Id -ne $SubscriptionId) {
    $null = Set-SIAzContext -Subscription $SubscriptionId
    $azCtx = Get-SISetupAzureContext
}
_Ok ("Azure sign-in: {0} (sub: {1} / {2})" -f $azCtx.Account.Id, $azCtx.Subscription.Name, $azCtx.Subscription.Id)

$rbacScopes  = @()
$rbacResults = @()                # @{Name; Scope; Status; Error}
$rootMgScope = "/providers/Microsoft.Management/managementGroups/$RootMgId"
$subScope    = "/subscriptions/$SubscriptionId"

# Build the role list for tenant-root MG. Reader is always included (drives
# subscription discovery + cross-sub LA queries). Tag Contributor is OPT-IN
# only when -IncludeTagContributor is set -- it's needed exclusively by the
# asset-exclusion-tagging engine, which most customers don't run. Granting
# Tag Contributor at tenant-root MG by default is too broad: it lets the SPN
# write tags to every resource in every subscription in the tenant.
$tenantRolePairs = @(@{Name='Reader'})
if ($IncludeTagContributor) {
    $tenantRolePairs += @{Name='Tag Contributor'}
}

if ($SkipTenantRbac) {
    $rolesSkipped = ($tenantRolePairs | ForEach-Object { $_.Name }) -join ' + '
    _Info ("SkipTenantRbac set -- skipping {0} at tenant-root MG" -f $rolesSkipped)
    foreach ($pair in $tenantRolePairs) {
        $rbacResults += @{ Name = $pair.Name; Scope = $rootMgScope; Status = 'skipped'; Error = 'SkipTenantRbac set' }
    }
} else {
    foreach ($pair in $tenantRolePairs) {
        $existing = @(Get-SIAzRoleAssignment -ObjectId $sp.Id -Scope $rootMgScope -RoleDefinitionName $pair.Name -ErrorAction SilentlyContinue) | Select-Object -First 1
        if ($existing) {
            _Info ("RBAC {0} already in place at root MG" -f $pair.Name)
            $rbacResults += @{ Name = $pair.Name; Scope = $rootMgScope; Status = 'already'; Error = $null }
            continue
        }
        try {
            $null = New-SIRoleAssignment -ObjectId $sp.Id -RoleDefinitionName $pair.Name -Scope $rootMgScope -PrincipalType ServicePrincipal
            _Ok ("RBAC {0} granted at root MG" -f $pair.Name)
            $rbacScopes += "$rootMgScope|$($pair.Name)"
            $rbacResults += @{ Name = $pair.Name; Scope = $rootMgScope; Status = 'granted'; Error = $null }
        } catch {
            $errMsg = $_.Exception.Message
            _Warn ("RBAC {0} grant failed: {1}" -f $pair.Name, $errMsg)
            $rbacResults += @{ Name = $pair.Name; Scope = $rootMgScope; Status = 'pending'; Error = $errMsg }
        }
    }
}

# v2.2.354 -- Contributor at the target subscription (where SI is installed).
# Customer ask: "set only READ on mgmt root and then contributor on the
# subscription defined where SI will be installed". Replaces the implicit
# expectation that downstream Initialize-SIInfra's granular RG/workspace/
# storage grants would suffice -- subscription-scope Contributor covers all of
# those + workspace ops + DCR/DCE provisioning + storage account create + RBAC
# delegation, in one assignment. Granular grants in Initialize-SIInfra stay
# (they no-op when inherited from sub-scope -- defensive idempotency).
$existingSubContrib = @(Get-SIAzRoleAssignment -ObjectId $sp.Id -Scope $subScope -RoleDefinitionName 'Contributor' -ErrorAction SilentlyContinue |
                       Where-Object { $_.Scope -eq $subScope }) | Select-Object -First 1
if ($existingSubContrib) {
    _Info ("RBAC Contributor already in place at subscription {0}" -f $SubscriptionId)
    $rbacResults += @{ Name = 'Contributor'; Scope = $subScope; Status = 'already'; Error = $null }
} else {
    try {
        $null = New-SIRoleAssignment -ObjectId $sp.Id -RoleDefinitionName 'Contributor' -Scope $subScope -PrincipalType ServicePrincipal
        _Ok ("RBAC Contributor granted at subscription {0}" -f $SubscriptionId)
        $rbacScopes += "$subScope|Contributor"
        $rbacResults += @{ Name = 'Contributor'; Scope = $subScope; Status = 'granted'; Error = $null }
    } catch {
        $errMsg = $_.Exception.Message
        _Warn ("RBAC Contributor at subscription {0} failed: {1} (operator likely needs Owner OR Contributor + User Access Administrator on that subscription)" -f $SubscriptionId, $errMsg)
        $rbacResults += @{ Name = 'Contributor'; Scope = $subScope; Status = 'pending'; Error = $errMsg }
    }
}

# ----- 7. Cred storage -----
$credValue        = $null
$kvOut            = $null
$kvSecretOut      = $null
$kvCertOut        = $null
$certThumbprintOut= $null
$expiresOut       = $null

if ($UseExistingAppId) {
    # Existing v1 cert in local store; we don't generate / move / store anything.
    # CertThumbprint surfaces in the result so the caller can confirm parity
    # with what they passed in.
    $certThumbprintOut = $ExistingThumbprint
    _Info "cred storage = ExistingCert -- v1 cert in local store; nothing written"
}
elseif ($CredKind -eq 'Secret') {
    if ($CredStorage -eq 'KeyVault') {
        _Step "store secret in Key Vault"
        $kv = Get-SIKeyVault -VaultName $KeyVaultName -SubscriptionId $SubscriptionId -ErrorAction SilentlyContinue
        if (-not $kv) { throw "Key Vault '$KeyVaultName' not found in subscription $SubscriptionId" }
        # PUT a new version of the secret, with the app secret's own expiry (data plane, as the signed-in identity)
        $kvBody = @{ value = $pwd.SecretText; attributes = @{ exp = [long]([DateTimeOffset]$pwd.EndDateTime.ToUniversalTime()).ToUnixTimeSeconds() } } | ConvertTo-Json -Compress
        $null = Invoke-SIAzRestRequest -Method PUT -Uri ('https://{0}.vault.azure.net/secrets/{1}?api-version=7.4' -f $KeyVaultName, [uri]::EscapeDataString($KvSecretName)) `
                    -Audience KeyVault -Body $kvBody -What ("Key Vault secret '{0}' in '{1}'" -f $KvSecretName, $KeyVaultName)
        _Ok ("secret stored at https://{0}.vault.azure.net/secrets/{1}" -f $KeyVaultName, $KvSecretName)
        $kvOut = $KeyVaultName; $kvSecretOut = $KvSecretName
    } else {
        _Info 'cred storage = Inline -- secret returned in result object (DO NOT log)'
        $credValue = $pwd.SecretText
    }
    $expiresOut = $pwd.EndDateTime.ToUniversalTime()
}
elseif ($CredKind -eq 'Cert') {
    $certThumbprintOut = $certInfo.Thumbprint
    $expiresOut        = $certInfo.NotAfter.ToUniversalTime()
    if ($CredStorage -eq 'KeyVault') {
        _Step "store cert .pfx in Key Vault"
        $kv = Get-SIKeyVault -VaultName $KeyVaultName -SubscriptionId $SubscriptionId -ErrorAction SilentlyContinue
        if (-not $kv) { throw "Key Vault '$KeyVaultName' not found in subscription $SubscriptionId" }
        if (-not $certInfo.PfxBytes) {
            # A re-used certificate whose private key is not exportable. It is only acceptable if the vault
            # already holds this very certificate; otherwise say so instead of uploading nothing.
            $kvCert = Get-SIKeyVaultCertificate -VaultName $KeyVaultName -Name $KvCertName -ErrorAction SilentlyContinue
            if ($kvCert -and ($kvCert.Thumbprint -eq $certInfo.Thumbprint)) {
                _Ok ("Key Vault already holds this certificate ({0}) -- nothing to upload" -f $certInfo.Thumbprint)
                $kvOut = $KeyVaultName; $kvCertOut = $KvCertName
            } else {
                throw ("The certificate {0} on this host is not exportable, and Key Vault '{1}' does not hold it as '{2}'. Upload it to the vault manually, or use -CredStorage LocalCertStore." -f $certInfo.Thumbprint, $KeyVaultName, $KvCertName)
            }
        } else {
            # the PFX goes straight from memory to the vault's data plane -- never written to disk
            $null = Import-SIKeyVaultCertificate -VaultName $KeyVaultName -Name $KvCertName -CertificateBytes $certInfo.PfxBytes -Password ([string]$certInfo.PfxPassword)
            _Ok ("cert stored at https://{0}.vault.azure.net/certificates/{1}" -f $KeyVaultName, $KvCertName)
            $kvOut     = $KeyVaultName
            $kvCertOut = $KvCertName
        }
    } elseif ($CredStorage -eq 'LocalCertStore') {
        _Info ("cert kept in LocalMachine\My (thumbprint $($certInfo.Thumbprint)) -- private key stays on this machine only, visible to any account on this host")
        # Already in LocalMachine\My from New-SelfSignedCertificate (v2.2.243). Nothing else to do.
    }
}
elseif ($CredKind -eq 'ManagedIdentity') {
    _Info "MSI mode: app-reg cred not generated. The launcher must run on the host that owns this MSI."
    $expiresOut = $null
}

Write-Host ""
[pscustomobject]@{
    AppId             = $app.AppId
    ObjectId          = $sp.Id
    TenantId          = $TenantId
    DisplayName       = $DisplayName
    CredKind          = $CredKind
    CredValue         = $credValue          # Secret + Inline only
    CertThumbprint    = $certThumbprintOut  # Cert path only
    KvName            = $kvOut
    KvSecretName      = $kvSecretOut        # Secret-in-KV
    KvCertName        = $kvCertOut          # Cert-in-KV
    ManagedIdentityId = if ($CredKind -eq 'ManagedIdentity') { $ManagedIdentityClientId } else { $null }
    ExpiresUtc        = $expiresOut
    GraphPermissions  = $GraphPermissions
    GraphPermissionResults = $permResults    # @[{Name; Status; Error}, ...]
    PendingPermissions     = ($permResults | Where-Object { $_.Status -in @('pending','skipped') } | ForEach-Object { $_.Name })
    ConsentStatus          = $consentStatus  # granted | partial | pending
    ConsentUrl             = $consentUrl     # hand to a Global Admin
    AzureRbacScopes        = $rbacScopes
    AzureRbacResults       = $rbacResults    # @[{Name; Scope; Status; Error}, ...]
}
