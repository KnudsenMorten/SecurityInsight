#Requires -Version 7.0
<#
    EVERY RECOMMENDATION / CVE FINDING TAKES TIER, CMDB AND EXCLUSION FROM THE ONE CI IT IS LINKED TO (#146 -> #505).

    History (#146, measured live 2026-09-28): the reports joined each finding to its PROFILE row by several links --
    strong key, name, ARM path, device short name -- and Tier, cmdb* and the exclusion flag came only from the strong
    key. 617/617 Azure_Recommendations_Detailed rows had no tier, cmdb* was empty, and a tag-excluded asset could stay
    in the findings. The fix carried every column across every fallback link.

    #505 removed the fallback chain itself: the finding is joined ONCE to _ciLink on the provider id it carries
    (`$left.DeviceKey == $right._ciKey`), and the CI holds the tier, the CMDB values and the tags. What is still worth
    protecting, re-expressed for the CI design:
      - the finding's CI join is the _ciLink join on the provider key, and no profile table / fallback link is read;
      - tier and cmdb* are the CI's (si_tier, si_cmdb_*), so they cannot come from one link and be missing on another;
      - the exclusion-tag filter reads the CI's tags and runs AFTER the CI join, so an excluded asset is really excluded;
      - the Azure reports: a subscription-level row no CI links takes the subscription's most critical CI (#192), and the
        Defender reports take the most critical of the resource, its subscription and its parent, nulls last (#190).
    Retired with the profile tables (V3-DATA-MODEL 2.21.1): the per-link Tier_By* / cmdb*_By* columns, the coalesce
    casts across links, the VM short-name bridge (_apVmByShort), the v3-vs-2.2 profile ranking and _devTier -- the CI
    links the VM's ARM id AND its Defender device id, so a VM and its machine are one CI with one tier.
#>

BeforeDiscovery {
    $script:Reports = @(
        @{ Name = 'Azure_Recommendations_Summary';   Tier = '| extend CriticalityTier = iff(isnull(si_tier) and isnotempty(_subK), toint(Tier_BySub), toint(si_tier))' }
        @{ Name = 'Azure_Recommendations_Detailed';  Tier = '| extend CriticalityTier = iff(isnull(si_tier) and isnotempty(_subK), toint(Tier_BySub), toint(si_tier))' }
        @{ Name = 'Device_Missing_CVEs_Summary';     Tier = '| extend CriticalityTier = toint(si_tier)' }
        @{ Name = 'Device_Missing_CVEs_Detailed';    Tier = '| extend CriticalityTier = toint(si_tier)' }
        @{ Name = 'Device_Recommendations_Summary';  Tier = '| extend CriticalityTier = toint(si_tier)' }
        @{ Name = 'Device_Recommendations_Detailed'; Tier = '| extend CriticalityTier = toint(si_tier)' }
    )
}

BeforeAll {
    $script:SIRoot = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSCommandPath))
    $yamlPath = Join-Path $script:SIRoot 'risk-analysis-detection\RiskAnalysis_Queries_Locked.yaml'
    $script:Yaml = [IO.File]::ReadAllText($yamlPath)
    function script:Get-ReportQuery([string]$Name) {
        # The report's query text only (its ReportPurpose prose may still describe the history).
        $b = [regex]::Match($script:Yaml, '(?s)- ReportName: ' + [regex]::Escape($Name) + '\r?\n(.*?)(?=\r?\n    - ReportName: |\z)').Groups[1].Value
        $i = $b.IndexOf('ReportQuery:')
        if ($i -lt 0) { return '' }
        $b.Substring($i)
    }
    $script:CiJoin  = '| join kind=leftouter (_ciLink) on $left.DeviceKey == $right._ciKey'
    # #541: the exclusion tags are a scope part -- the CI link block marks each CI si_in_scope_ (its tags against the
    # exclusion tags, generated by the engine) and the report keeps the CIs in scope right after its join
    $script:TagDrop = '| where coalesce(si_in_scope_, true)'
    $script:TagScope = 'not(si_tags_ has_any (dynamic('
}

Describe 'report <Name>: one CI link carries tier, CMDB and exclusion' -ForEach $script:Reports {
    BeforeAll { $script:Q = Get-ReportQuery $Name }

    It 'the report query was found (control)' {
        $script:Q | Should -Match '_ciLink' -Because "$Name must be in the locked catalog and read the CI"
    }
    It 'the finding is joined to its CI exactly once, on the provider key' {
        ([regex]::Matches($script:Q, [regex]::Escape($script:CiJoin))).Count | Should -Be 1
    }
    It 'no profile table and no fallback link is read' {
        $script:Q | Should -Not -Match 'SI_\w+_Profile_CL'
        $script:Q | Should -Not -Match '\b\w+_By(Name|Path|Vm|Dev)\b' -Because 'the per-link fallback columns are gone with the profile'
    }
    It 'tier is the CI tier, nulls handled by the case() default' {
        $script:Q | Should -Match ([regex]::Escape($Tier))
        # #690 (15): the default is BLANK -- a CI without a tier is kept by the scope filter and given its tier by the rules,
        # never labelled "Low - tier 3"
        $script:Q | Should -Match 'CriticalityTier == 3, "Low - tier 3",\s*""\)'
        $script:Q | Should -Not -Match ([regex]::Escape('"Low - tier 3")'))
    }
    It 'cmdb* are the CI''s CMDB values' {
        $script:Q | Should -Match ([regex]::Escape('| extend cmdbId = tostring(si_cmdb_id), cmdbName = tostring(si_cmdb_name), cmdbCriticality = tostring(si_cmdb_criticality), cmdbDataSensitivity = tostring(si_cmdb_data_sensitivity)'))
    }
    It 'the exclusion-tag filter reads the CI tags and runs AFTER the CI join, so an excluded asset is really excluded' {
        $j  = $script:Q.IndexOf($script:CiJoin)
        $ex = $script:Q.IndexOf($script:TagDrop)
        $j  | Should -BeGreaterThan 0
        $ex | Should -BeGreaterThan $j
        $script:Q | Should -Match ([regex]::Escape('| extend si_in_scope_ = ')) -Because 'the CI link block carries the scope (#541)'
        $script:Q.IndexOf($script:TagScope) | Should -BeGreaterThan 0 -Because 'the CI tags are tested against the exclusion tags in the link block'
    }
}

Describe 'an Azure finding reaches the most critical tier its scope gives it (#190 / #192, CI design)' {
    BeforeAll {
        function script:Get-Q([string]$Name) { Get-ReportQuery $Name }
    }
    It '<_>: a subscription-level row no CI links takes the subscription''s most critical CI' -ForEach @('Azure_Recommendations_Summary', 'Azure_Recommendations_Detailed') {
        $b = Get-Q $_
        # #675: read on its own (a canonical CI block), never from the per-slice _ciLink
        $b | Should -Match '//__SI_CI_SUBTIER_BEGIN__'
        $b | Should -Not -Match 'let _subTierG = _ciLink'
        $b | Should -Match ([regex]::Escape('| summarize Tier_BySub = min(toint(column_ifexists("si_tier", int(null)))) by _sub;'))
        $b.IndexOf('| join kind=leftouter (_subTierG)') | Should -BeGreaterThan 0
        $b.IndexOf('| join kind=leftouter (_subTierG)') | Should -BeLessThan $b.IndexOf('| extend CriticalityTier = ')
    }
    It '<_>: resource, subscription and parent -- the most critical wins (nulls last)' -ForEach @('Azure_DefenderRecommendations_Summary', 'Azure_DefenderRecommendations_Detailed') {
        $b = Get-Q $_
        $b | Should -Match ([regex]::Escape('| extend CriticalityTier = toint(array_sort_asc(pack_array(toint(si_tier), toint(Tier_BySub), toint(Tier_ByParent)))[0])'))
        $b | Should -Match ([regex]::Escape('| join kind=leftouter (_ciLink) on $left._k == $right._ciKey'))
        # #690 (14): the subscription tier from its own canonical block (the #675 fix), never from the per-slice _ciLink
        $b | Should -Match '//__SI_CI_SUBTIER_BEGIN__'
        $b | Should -Not -Match 'let _subTier = _ciLink'
        $b | Should -Match ([regex]::Escape('| summarize Tier_BySub = min(toint(column_ifexists("si_tier", int(null)))) by _sub;')) -Because 'one row per subscription, so the join cannot duplicate findings'
        $b.IndexOf('| join kind=leftouter (_subTierG) on _sub') | Should -BeGreaterThan 0
        $b.IndexOf('| join kind=leftouter (_subTierG) on _sub') | Should -BeLessThan $b.IndexOf('| extend CriticalityTier = ')
        $b | Should -Match ([regex]::Escape('| join kind=leftouter (_ciLink | project _kp = _ciKey, Tier_ByParent = si_tier) on _kp'))
        $b | Should -Not -Match 'SI_\w+_Profile_CL'
        $b | Should -Not -Match '(?m)^\s*//[^\r\n]*:' -Because 'a colon in a // comment inside the YAML block breaks the parse'
    }
}
