#Requires -Version 7.0
<#
    THE SETTINGS CATALOG IS EXACTLY WHAT ITS BUILDER MAKES (2026-11-23). config\settings.catalog.locked.json and the SETTINGS
    GLOSSARY at the end of config\SecurityInsight.custom.sample.reference.ps1 are GENERATED by engine\pro-settings\
    Build-SISettingsCatalog.ps1. A hand edit -- or a merge that resolved a conflict by hand -- that the builder would not
    write is lost at the next rebuild (seen 2026-11-23: a merge left SI_Mail_Mode with its "valueLabels" and "editor" twice;
    the builder writes them once, from its own source).
    What this file pins:
      * the builder, run on a copy of its sources (config + launcher), writes the committed catalog and glossary EXACTLY
        (line endings aside) -- any difference fails, with the first differing lines;
      * every choice label and editor in the catalog comes from a source the builder reads (descriptions help section,
        or the builder's own per-setting table) -- none lives only in the catalog;
      * no object of the committed catalog carries a key twice.
    Offline: the builder reads files only.
#>

BeforeAll {
    $script:SIRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
    $script:Copy = Join-Path ([IO.Path]::GetTempPath()) ('si-catalog-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $script:Copy | Out-Null
    foreach ($d in 'config', 'launcher') { Copy-Item -LiteralPath (Join-Path $script:SIRoot $d) -Destination (Join-Path $script:Copy $d) -Recurse }
    $builder = Join-Path $script:SIRoot 'engine\pro-settings\Build-SISettingsCatalog.ps1'
    $script:BuildOut = & pwsh -NoProfile -File $builder -SIRoot $script:Copy 2>&1 | Out-String
    $script:BuildExit = $LASTEXITCODE
    function script:Norm([string]$Path) { ([IO.File]::ReadAllText($Path)) -replace "`r`n", "`n" }
    function script:FirstDiff([string]$A, [string]$B) {
        # (own names: PowerShell names are case-insensitive, so $a would be the [string] parameter $A, joined back to one string)
        [string[]]$la = $A -split "`n"; [string[]]$lb = $B -split "`n"
        for ($i = 0; $i -lt [Math]::Max($la.Count, $lb.Count); $i++) {
            $x = if ($i -lt $la.Count) { $la[$i] } else { '<end>' }; $y = if ($i -lt $lb.Count) { $lb[$i] } else { '<end>' }
            if ($x -ne $y) { return ('line {0}: committed [{1}] / generated [{2}]' -f ($i + 1), $x.Trim(), $y.Trim()) }
        }
        ''
    }
    function script:Get-DupKeys([string]$Json) {
        $doc = [System.Text.Json.JsonDocument]::Parse($Json)
        $dups = New-Object System.Collections.Generic.List[string]
        $walk = $null
        $walk = {
            param($el, [string]$at)
            if ($el.ValueKind -eq [System.Text.Json.JsonValueKind]::Object) {
                $seen = New-Object 'System.Collections.Generic.HashSet[string]'
                foreach ($p in $el.EnumerateObject()) {
                    if (-not $seen.Add($p.Name)) { $dups.Add(('{0}.{1}' -f $at, $p.Name)) }
                    $n = if ($p.Name -eq 'name') { $at } else { $at + '.' + $p.Name }
                    & $walk $p.Value $n
                }
            } elseif ($el.ValueKind -eq [System.Text.Json.JsonValueKind]::Array) {
                $i = 0
                foreach ($x in $el.EnumerateArray()) {
                    $lbl = $at + '[' + $i + ']'
                    if ($x.ValueKind -eq [System.Text.Json.JsonValueKind]::Object) {
                        foreach ($q in $x.EnumerateObject()) { if ($q.Name -eq 'name' -and $q.Value.ValueKind -eq [System.Text.Json.JsonValueKind]::String) { $lbl = $at + '[' + $q.Value.GetString() + ']'; break } }
                    }
                    & $walk $x $lbl; $i++
                }
            }
        }
        try { & $walk $doc.RootElement '' } finally { $doc.Dispose() }
        $dups.ToArray()
    }
}

AfterAll {
    if ($script:Copy -and (Test-Path -LiteralPath $script:Copy)) { Remove-Item -LiteralPath $script:Copy -Recurse -Force -ErrorAction SilentlyContinue }
}

Describe 'the settings catalog is generated, never edited by hand' {
    It 'the builder runs on a copy of its sources' {
        $script:BuildExit | Should -Be 0 -Because $script:BuildOut
        $script:BuildOut | Should -Match 'settings catalog: \d+ settings'
    }
    It 'GENERATED = COMMITTED: the catalog -- re-run Build-SISettingsCatalog.ps1 (on the test runner) and commit its output when this fails' {
        $c = Norm (Join-Path $script:SIRoot 'config\settings.catalog.locked.json')
        $g = Norm (Join-Path $script:Copy 'config\settings.catalog.locked.json')
        $d = FirstDiff $c $g
        if ($d) { throw ('the committed catalog is not what the builder writes (a line the builder does not write is lost at the next rebuild) -- ' + $d) }
    }
    It 'GENERATED = COMMITTED: the glossary in the Community reference' {
        $c = Norm (Join-Path $script:SIRoot 'config\SecurityInsight.custom.sample.reference.ps1')
        $g = Norm (Join-Path $script:Copy 'config\SecurityInsight.custom.sample.reference.ps1')
        $d = FirstDiff $c $g
        if ($d) { throw ('the committed glossary is not what the builder writes -- ' + $d) }
    }
    It 'no object of the committed catalog carries a key twice' {
        $dups = @(Get-DupKeys ([IO.File]::ReadAllText((Join-Path $script:SIRoot 'config\settings.catalog.locked.json'))))
        if ($dups.Count) { throw ('keys written twice: ' + (($dups | Select-Object -First 8) -join ', ')) }
        ($dups -join ', ') | Should -BeExactly ''
    }
    It 'NEGATIVE: the checks fail on a drift -- one changed line, one key written twice' {
        $c = Norm (Join-Path $script:SIRoot 'config\settings.catalog.locked.json')
        (FirstDiff $c ($c.Replace('"editor": "radio"', '"editor": "dropdown"'))) | Should -Match '^line \d+: committed'
        @(Get-DupKeys '{"settings":[{"name":"X","editor":"radio","editor":"radio"}]}') | Should -Be @('.settings[X].editor')
        @(Get-DupKeys '{"settings":[{"name":"X","editor":"radio"}]}').Count | Should -Be 0
        (FirstDiff "a
b" "a
b") | Should -BeExactly '' -Because 'the same text: no difference (control)'
        (FirstDiff "a
b" "a
c") | Should -BeExactly 'line 2: committed [b] / generated [c]'
    }
    It 'every choice label and editor comes from a source the builder reads -- none lives only in the catalog' {
        $cat = Get-Content -Raw (Join-Path $script:SIRoot 'config\settings.catalog.locked.json') | ConvertFrom-Json
        $help = (Get-Content -Raw (Join-Path $script:SIRoot 'config\settings.descriptions.locked.json') | ConvertFrom-Json).help
        $builderText = [IO.File]::ReadAllText((Join-Path $script:SIRoot 'engine\pro-settings\Build-SISettingsCatalog.ps1'))
        $with = @($cat.settings | Where-Object { $_.PSObject.Properties['valueLabels'] -or $_.PSObject.Properties['editor'] })
        $with.Count | Should -BeGreaterThan 0
        foreach ($s in $with) {
            $inHelp = [bool]($help.PSObject.Properties[$s.name] -and ($help.($s.name).PSObject.Properties['valueLabels'] -or $help.($s.name).PSObject.Properties['editor']))
            $inBuilder = $builderText -match ('(?m)^\s*' + [regex]::Escape($s.name) + '\s*=\s*@\{[^\r\n]*(valueLabels|editor)')
            ($inHelp -or $inBuilder) | Should -BeTrue -Because "$($s.name): its labels / editor must come from the descriptions help or the builder's table"
        }
        # SI_Mail_Mode in particular: the radio buttons and their plain words
        $m = @($cat.settings | Where-Object { $_.name -eq 'SI_Mail_Mode' })[0]
        $m.editor | Should -Be 'radio'
        @($m.valueLabels.PSObject.Properties.Name) | Should -Be @('sharedMailbox', 'smtp', 'none')
    }
}
