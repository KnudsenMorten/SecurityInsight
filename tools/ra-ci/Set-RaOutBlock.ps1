#Requires -Version 5.1
<#
.SYNOPSIS
    Writes the generated data-out block (//__SI_OUT_BEGIN__ ... //__SI_OUT_END__) at the end of EVERY query report of
    risk-analysis-detection/RiskAnalysis_Queries_Locked.yaml (REQUIREMENTS #692 (c) / (d)), keeping the YAML around it byte
    for byte. Run it after a report's OutputPropertyOrder, its query or the field catalog's row-column map changed.

.DESCRIPTION
    The block is generated by engine/risk-analysis/_shared/RA-OutBlock.ps1 (Update-RAOutBlocksInCatalog) -- never hand-edit
    it. -Check changes nothing and exits 1 when a report's block is missing or differs (the guard test does the same).
    A change of the block changes the report's fingerprint: a NEW block content is a structure-only change only while it
    stays inside //__SI_OUT_BEGIN__ / //__SI_OUT_END__ (data-model/report-fingerprint-carry.locked.json takes the block out
    when it computes the fingerprint the report had before #692).
.EXAMPLE
    .\tools\ra-ci\Set-RaOutBlock.ps1 -Check
    .\tools\ra-ci\Set-RaOutBlock.ps1
#>
[CmdletBinding()]
param([switch]$Check, [string]$YamlPath)
$ErrorActionPreference = 'Stop'
$siRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not $YamlPath) { $YamlPath = Join-Path $siRoot 'risk-analysis-detection\RiskAnalysis_Queries_Locked.yaml' }
. (Join-Path $siRoot 'engine\risk-analysis\_shared\RA-OutBlock.ps1')

$raw = [IO.File]::ReadAllText($YamlPath)
$r = Update-RAOutBlocksInCatalog -Yaml $raw
if ($Check) {
    if (@($r.Changed).Count) { Write-Output ('{0} of {1} report(s) need their data-out block written: {2}' -f @($r.Changed).Count, @($r.Reports).Count, (@($r.Changed) -join ', ')); exit 1 }
    Write-Output ('every one of the {0} query reports carries its generated data-out block' -f @($r.Reports).Count)
    exit 0
}
if (@($r.Changed).Count -eq 0) { Write-Output ('nothing to write -- every one of the {0} query reports carries its generated data-out block' -f @($r.Reports).Count); return }
[IO.File]::WriteAllText($YamlPath, $r.Text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ('data-out block written for {0} of {1} query report(s)' -f @($r.Changed).Count, @($r.Reports).Count)
